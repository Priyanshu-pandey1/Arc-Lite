@app.route("/api/faqs/<int:faq_id>", methods=["PUT"])
@staff_required
def update_faq(faq_id):
    data = request.get_json(silent=True)
    faq_data, error = validate_faq_input(data)

    if error:
        return jsonify({"error": error}), 400

    try:
        with g.db_conn.cursor() as cur:
            cur.execute(
                """
                UPDATE faq_entries
                SET question = %s,
                    category = %s,
                    canonical_answer = %s,
                    is_active = %s,
                    updated_at = NOW()
                WHERE id = %s
                RETURNING id, question, category,
                          canonical_answer, is_active, updated_at;
                """,
                (
                    faq_data["question"],
                    faq_data["category"],
                    faq_data["answer"],
                    faq_data["status"] == "active",
                    faq_id,
                ),
            )
            row = cur.fetchone()

            if row is None:
                return jsonify({
                    "error": "FAQ not found."
                }), 404

        # Commit before the AI index refresh (see create_faq).
        g.db_conn.commit()

        refresh_assistant()

        return jsonify(format_faq(row)), 200

    except Exception:
        app.logger.exception("Failed to update FAQ")
        return jsonify({
            "error": "Unable to update FAQ."
        }), 500


